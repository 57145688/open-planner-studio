/**
 * 把上游真实样例（23.8 MB LiDAR 点云 + IFC2X3 模型）整理为仓库内可分发的小体积案例。
 *
 * 用法：npx tsx scripts/prepare-reality-case.ts [voxel]
 * 默认 4 cm 体素，输出 examples/reality/Sample.scan.ply、Sample.ifc、case.json。
 */
import { copyFileSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parsePly, voxelDownsample } from '../packages/core/src/realcase';
import type { ParsedPointCloud } from '../packages/core/src/realcase';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = resolve(root, 'vendor/pcd-bim-sample/input');
const outDir = resolve(root, 'examples/reality');
const voxel = Number(process.argv[2] ?? 0.04);

const sourcePly = resolve(sourceDir, 'Sample.ply');
const sourceIfc = resolve(sourceDir, 'Sample.ifc');

const cloud: ParsedPointCloud = parsePly(readFileSync(sourcePly), { voxel });
const outputPly = resolve(outDir, 'Sample.scan.ply');
const outputIfc = resolve(outDir, 'Sample.ifc');

mkdirSync(outDir, { recursive: true });

const header = [
  'ply',
  'format binary_little_endian 1.0',
  'comment Real LiDAR sample from CyberbuildLab/pcd-bim-matching-confidence (Apache-2.0)',
  `comment Voxel downsampled ${voxel} m by APCC scripts/prepare-reality-case.ts`,
  `element vertex ${cloud.pointCount}`,
  'property float x',
  'property float y',
  'property float z',
  'property uchar red',
  'property uchar green',
  'property uchar blue',
  'end_header',
  '',
].join('\n');

const body = Buffer.alloc(cloud.pointCount * 15);
cloud.points.forEach((point, index) => {
  const offset = index * 15;
  body.writeFloatLE(point.x, offset);
  body.writeFloatLE(point.y, offset + 4);
  body.writeFloatLE(point.z, offset + 8);
  body.writeUInt8(point.r, offset + 12);
  body.writeUInt8(point.g, offset + 13);
  body.writeUInt8(point.b, offset + 14);
});
writeFileSync(outputPly, Buffer.concat([Buffer.from(header, 'ascii'), body]));
copyFileSync(sourceIfc, outputIfc);

/**
 * 3DGS 格式验证样本：把实测点云转换为带 f_dc_*、opacity、scale、rot 的 PLY。
 * 这不是训练出来的高斯，只用于验证 3DGS 格式解析与对比链路。
 */
const SH_C0 = 0.28209479177387814;
const gaussianPoints = voxelDownsample(cloud.points, 0.09).slice(0, 90_000);
const output3dgs = resolve(outDir, 'Sample.3dgs.ply');
const gaussianHeader = [
  'ply',
  'format binary_little_endian 1.0',
  'comment 3DGS-format verification sample converted from the real LiDAR cloud (not a trained result)',
  `comment Voxel 0.09 m, ${gaussianPoints.length} points, generated by APCC scripts/prepare-reality-case.ts`,
  `element vertex ${gaussianPoints.length}`,
  'property float x',
  'property float y',
  'property float z',
  'property float f_dc_0',
  'property float f_dc_1',
  'property float f_dc_2',
  'property float opacity',
  'property float scale_0',
  'property float scale_1',
  'property float scale_2',
  'property float rot_0',
  'property float rot_1',
  'property float rot_2',
  'property float rot_3',
  'end_header',
  '',
].join('\n');
const gaussianStride = 56;
const gaussianBody = Buffer.alloc(gaussianPoints.length * gaussianStride);
gaussianPoints.forEach((point, index) => {
  const offset = index * gaussianStride;
  gaussianBody.writeFloatLE(point.x, offset);
  gaussianBody.writeFloatLE(point.y, offset + 4);
  gaussianBody.writeFloatLE(point.z, offset + 8);
  // 3DGS 使用球谐直流项存颜色，这里按标准 SH_C0 反算
  gaussianBody.writeFloatLE((point.r / 255 - 0.5) / SH_C0, offset + 12);
  gaussianBody.writeFloatLE((point.g / 255 - 0.5) / SH_C0, offset + 16);
  gaussianBody.writeFloatLE((point.b / 255 - 0.5) / SH_C0, offset + 20);
  gaussianBody.writeFloatLE(2.9, offset + 24);
  gaussianBody.writeFloatLE(-3.0, offset + 28);
  gaussianBody.writeFloatLE(-3.0, offset + 32);
  gaussianBody.writeFloatLE(-3.0, offset + 36);
  gaussianBody.writeFloatLE(1, offset + 40);
  gaussianBody.writeFloatLE(0, offset + 44);
  gaussianBody.writeFloatLE(0, offset + 48);
  gaussianBody.writeFloatLE(0, offset + 52);
});
writeFileSync(output3dgs, Buffer.concat([Buffer.from(gaussianHeader, 'ascii'), gaussianBody]));

const caseMeta = {
  id: 'pcd-bim-sample',
  title: '真实扫描点云 vs IFC 设计模型',
  subtitle: 'Apache-2.0 学术样例：单层空间，7 段墙、2 块吊顶、2 樘门',
  dataKind: 'lidar-point-cloud + 3dgs-format',
  defaultTolerance: 0.1,
  source: {
    repository: 'CyberbuildLab/pcd-bim-matching-confidence',
    url: 'https://github.com/CyberbuildLab/pcd-bim-matching-confidence',
    license: 'Apache-2.0',
    citation:
      'Ersoz, A. B. & Bosché, F. Evaluating confidence in geometric matching between 3D point clouds and BIM models. Automation in Construction 181 (2026) 106636.',
    doi: 'https://doi.org/10.1016/j.autcon.2025.106636',
    originalFiles: [
      'input/Sample.ply：23,826,107 字节，1,588,386 点，CloudCompare 2025-01-05 导出',
      'input/Sample.ifc：IFC2X3，48,125 字节，11 个可解析网格',
    ],
  },
  processing: {
    tool: 'scripts/prepare-reality-case.ts',
    method: `体素降采样 ${voxel} m，坐标与颜色取体素均值`,
    sourcePoints: cloud.sourcePointCount,
    points: cloud.pointCount,
    outputBytes: statSync(outputPly).size,
    format: cloud.format,
    gaussianSplatColors: cloud.gaussianSplatColors,
  },
  epochs: [
    {
      id: '2025-01-05',
      label: '2025-01-05 实测扫描',
      date: '2025-01-05',
      kind: 'lidar',
      capture: '上游样例，CloudCompare v2.13.2 导出的配准后点云；采集设备与精度未在上游文档说明',
      sourcePoints: cloud.sourcePointCount,
      points: cloud.pointCount,
      bounds: cloud.bounds,
    },
  ],
  files: {
    scan: '/api/reality/case/scan.ply',
    model: '/api/reality/case/model.ifc',
    verify3dgs: '/api/reality/case/scan.3dgs.ply',
  },
  verification: {
    label: '3DGS 格式验证样本',
    file: 'Sample.3dgs.ply',
    points: gaussianPoints.length,
    bytes: statSync(output3dgs).size,
    method:
      '由实测 LiDAR 点云按 0.09 m 体素降采样，颜色转换为 3DGS 的 f_dc_* 球谐直流项，并补齐 opacity / scale / rot 属性。',
    caveat:
      '该文件不是训练得到的高斯，仅用于验证 3DGS 格式解析、对比与界面链路；其覆盖率受点密度影响，不能作为 3DGS 重建精度结论。',
  },
  boundary:
    '主案例是实测 LiDAR 点云与 IFC 设计模型的几何对比，不是 3DGS 训练重建结果。仓库附带一个由实测点云转换的 3DGS 格式验证样本，并在界面中单独标注；真实 3DGS 训练导出的 .ply 可通过同一入口作为新一期数据上传。',
};

writeFileSync(resolve(outDir, 'case.json'), `${JSON.stringify(caseMeta, null, 2)}\n`);

console.log(
  `[reality-case] ${cloud.sourcePointCount} → ${cloud.pointCount} 点，` +
    `输出 ${(statSync(outputPly).size / 1024 / 1024).toFixed(2)} MB`,
);
console.log(
  `[reality-case] 包围盒 min=${cloud.bounds.min.map((n) => n.toFixed(2)).join(',')} ` +
    `max=${cloud.bounds.max.map((n) => n.toFixed(2)).join(',')}`,
);
console.log(
  `[reality-case] 3DGS 格式验证样本 ${gaussianPoints.length} 点，` +
    `${(statSync(output3dgs).size / 1024 / 1024).toFixed(2)} MB`,
);
